"""Author the audited, source-ordered learning sets for Chapters 55-57.

Source: uploads/04.pdf PDF61-76 = Book p686-701 and uploads/05.pdf PDF1 =
Book p702. No sheet carries a text layer and image review was unavailable in
this session, so every page was read line-to-line from RapidOCR transcripts
(.audit-render/ocr_0461.txt .. ocr_0476.txt, ocr_051.txt) with 8x-100x crops
and glyph-level re-reads used to settle every uncertain number, label and
table cell. The decode log and every resolved ambiguity are recorded in
audit/READ_NOTES_55_57.md.

Strictly book order. No fill-up, matching or true/false worksheets: only
recall, scenario, numeric, oddoneout and management formats, each with four
plausible medical options and a citation-backed explanation. The same call
that writes the chapter artifact also appends its ordered point -> question
ledger, so an inventoried point can never be silently dropped.
"""
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / "data"
LEDGER = ROOT / "audit" / "coverage.json"


def make_chapter(number, title, page_range, unit_specs):
    questions, units, ledger = [], [], []
    claimed = set()

    def claim(page, point, qid):
        key = (page, point)
        if key in claimed:
            return
        claimed.add(key)
        ledger.append({"chapter": number, "page": page, "point": point, "question": qid})

    for unit_no, (section, unit_title, guide, rows) in enumerate(unit_specs, 1):
        ids = []
        for page, fmt, stem, correct, distractors, explanation, points in rows:
            qid = f"MED-C{number}-{len(questions) + 1:02d}"
            choices = [correct, *distractors]
            shift = (len(questions) * 3 + number) % 4
            choices = choices[shift:] + choices[:shift]
            questions.append({
                "id": qid, "sec": section, "page": page, "fmt": fmt,
                "q": stem, "opts": choices, "ans": choices.index(correct),
                "exp": explanation + f" (Book p{page})",
            })
            assert (page, explanation) not in claimed, f"ch{number}: two questions share the point on p{page}: {explanation}"
            claim(page, explanation, qid)
            for point in points[1:]:
                claim(page, point, qid)
            ids.append(qid)
        units.append({
            "id": f"MED-U{number}-{unit_no}", "ch": number, "n": unit_no,
            "title": f"{unit_no}. {unit_title}", "sec": section,
            "guide": guide.replace("\\n", "\n"), "qs": ids,
        })
    pages = [q["page"] for q in questions]
    assert pages == sorted(pages), f"ch{number}: rows are not in book page order"
    covered = []
    for row in ledger:
        if not covered or covered[-1] != row["question"]:
            covered.append(row["question"])
    assert covered == [q["id"] for q in questions], f"ch{number}: ledger must run in question order"
    return {"chapter": number, "title": title, "pageRange": page_range,
            "questions": questions, "units": units}, ledger


def q(page, fmt, stem, correct, *distractors, exp, pts=None):
    assert len(distractors) == 3, f"{stem} needs 3 distractors got {distractors}"
    extra = [pt for pt in (pts or []) if pt != exp]
    return (page, fmt, stem, correct, list(distractors), exp, [exp, *extra])


def write(chapter, ledger):
    path = OUT / f"ch{chapter['chapter']:02d}.json"
    path.write_text(json.dumps(chapter, indent=2, ensure_ascii=False) + "\n", encoding="utf-8")
    rows = json.loads(LEDGER.read_text(encoding="utf-8"))
    number = chapter["chapter"]
    rows = [r for r in rows if r["chapter"] not in (number,)]
    first = int(chapter["pageRange"].split("-")[0])
    rows += [{"chapter": number, "page": r["page"], "point": r["point"], "question": r["question"]}
             for r in sorted(ledger, key=lambda x: x["page"])]
    rows.sort(key=lambda r: (r["chapter"], r["page"]))
    LEDGER.write_text(json.dumps(rows, indent=2, ensure_ascii=False) + "\n", encoding="utf-8")
    print(f"{path.name}: {len(chapter['questions'])} questions / {len(chapter['units'])} units; "
          f"ledger rows for ch{number}: {len(ledger)}; ledger total {len(rows)} (from page {first})")


